CREATE TABLE Equipes (
    id_equipe INT NOT NULL,
    Nome_equipe VARCHAR(100),
    Num_jogadores INT,
    PRIMARY KEY (id_equipe)
);

CREATE TABLE Jogos (
    id_jogo INT NOT NULL,
    Nome VARCHAR(100),
    Desenvolvedora VARCHAR(100),
    Tipo_jogo VARCHAR(500),
    PRIMARY KEY (id_jogo)
);

CREATE TABLE Campeonato (
    id_campeonato INT NOT NULL,
    Nome_campeonato VARCHAR(100),
    Formato VARCHAR(50),
    fk_Equipes_id_equipe INT,
    PRIMARY KEY (id_campeonato),
    FOREIGN KEY (fk_Equipes_id_equipe) REFERENCES Equipes(id_equipe)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

CREATE TABLE Jogadores (
    CPF INT NOT NULL,
    Nome_completo VARCHAR(100),
    Apelido VARCHAR(50),
    Conta_steam VARCHAR(100),
    Telefone NUMERIC,
    fk_Equipes_id_equipe INT,
    PRIMARY KEY (CPF),
    FOREIGN KEY (fk_Equipes_id_equipe) REFERENCES Equipes(id_equipe)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

CREATE TABLE Pontuacao (
    id_pontuacao INT GENERATED BY DEFAULT AS IDENTITY,
    N_vitoria INT,
    N_derrota INT,
    N_empate INT,
    N_kills INT,
    N_mortes INT,
    Dado_total DECIMAL(10, 2),
    Cura_total DECIMAL(10, 2),
    N_pontos DECIMAL(10, 2),
    fk_Equipes_id_equipe INT NOT NULL UNIQUE,
    PRIMARY KEY (id_pontuacao),
    FOREIGN KEY (fk_Equipes_id_equipe) REFERENCES Equipes(id_equipe)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

CREATE TABLE Partidas (
    id_partida INT NOT NULL,
    Num_rodada INT,
    fk_Campeonato_id_campeonato INT NOT NULL,
    fk_Jogos_id_jogo INT,
    PRIMARY KEY (id_partida),
    FOREIGN KEY (fk_Campeonato_id_campeonato) REFERENCES Campeonato(id_campeonato)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,
    FOREIGN KEY (fk_Jogos_id_jogo) REFERENCES Jogos(id_jogo)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

CREATE TABLE Resultados (
    id_resultado INT NOT NULL,
    resultado_partida DECIMAL(10, 2),
    kills INT,
    mortes INT,
    dano DECIMAL(10, 2),
    cura_realizada DECIMAL(10, 2),
    fk_Equipes_id_equipe INT,
    fk_Partidas_id_partida INT NOT NULL,
    PRIMARY KEY (id_resultado),
    FOREIGN KEY (fk_Equipes_id_equipe) REFERENCES Equipes(id_equipe)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,
    FOREIGN KEY (fk_Partidas_id_partida) REFERENCES Partidas(id_partida)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

CREATE OR REPLACE FUNCTION atualizar_pontuacao_equipe(p_id_equipe INT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_id_equipe IS NULL THEN
        RETURN;
    END IF;

    INSERT INTO Pontuacao (
        N_vitoria,
        N_derrota,
        N_empate,
        N_kills,
        N_mortes,
        Dado_total,
        Cura_total,
        N_pontos,
        fk_Equipes_id_equipe
    )
    SELECT
        COUNT(*) FILTER (
            WHERE r.resultado_partida > adversario.resultado_partida
        )::INT,
        COUNT(*) FILTER (
            WHERE r.resultado_partida < adversario.resultado_partida
        )::INT,
        COUNT(*) FILTER (
            WHERE r.resultado_partida = adversario.resultado_partida
        )::INT,
        COALESCE(SUM(COALESCE(r.kills, 0)), 0)::INT,
        COALESCE(SUM(COALESCE(r.mortes, 0)), 0)::INT,
        COALESCE(SUM(COALESCE(r.dano, 0)), 0),
        COALESCE(SUM(COALESCE(r.cura_realizada, 0)), 0),
        (
            COUNT(*) FILTER (
                WHERE r.resultado_partida > adversario.resultado_partida
            ) * 3
            + COUNT(*) FILTER (
                WHERE r.resultado_partida = adversario.resultado_partida
            )
        )::DECIMAL(10, 2),
        p_id_equipe
    FROM Resultados r
    JOIN (
        SELECT fk_Partidas_id_partida
        FROM Resultados
        GROUP BY fk_Partidas_id_partida
        HAVING COUNT(*) = 2
           AND COUNT(DISTINCT fk_Equipes_id_equipe) = 2
    ) partidas_validas
      ON partidas_validas.fk_Partidas_id_partida = r.fk_Partidas_id_partida
    JOIN Resultados adversario
      ON adversario.fk_Partidas_id_partida = r.fk_Partidas_id_partida
     AND adversario.fk_Equipes_id_equipe <> r.fk_Equipes_id_equipe
    WHERE r.fk_Equipes_id_equipe = p_id_equipe
    ON CONFLICT (fk_Equipes_id_equipe) DO UPDATE
    SET N_vitoria = EXCLUDED.N_vitoria,
        N_derrota = EXCLUDED.N_derrota,
        N_empate = EXCLUDED.N_empate,
        N_kills = EXCLUDED.N_kills,
        N_mortes = EXCLUDED.N_mortes,
        Dado_total = EXCLUDED.Dado_total,
        Cura_total = EXCLUDED.Cura_total,
        N_pontos = EXCLUDED.N_pontos;
END;
$$;

CREATE OR REPLACE FUNCTION trigger_recalcular_pontuacao()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    equipe_id INT;
    partida_antiga INT;
    partida_nova INT;
    equipe_antiga INT;
    equipe_nova INT;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        partida_antiga := OLD.fk_Partidas_id_partida;
        equipe_antiga := OLD.fk_Equipes_id_equipe;
    END IF;
    IF TG_OP <> 'DELETE' THEN
        partida_nova := NEW.fk_Partidas_id_partida;
        equipe_nova := NEW.fk_Equipes_id_equipe;
    END IF;

    FOR equipe_id IN
        SELECT DISTINCT equipe
        FROM (
            SELECT fk_Equipes_id_equipe AS equipe
            FROM Resultados
            WHERE fk_Partidas_id_partida IN (partida_antiga, partida_nova)
            UNION
            SELECT equipe_antiga
            UNION
            SELECT equipe_nova
        ) equipes_afetadas
        WHERE equipe IS NOT NULL
    LOOP
        PERFORM atualizar_pontuacao_equipe(equipe_id);
    END LOOP;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER atualizar_pontuacao_apos_resultado
AFTER INSERT OR UPDATE OR DELETE ON Resultados
FOR EACH ROW
EXECUTE FUNCTION trigger_recalcular_pontuacao();
